/**
 * 依學科名稱取得對應的答題技巧；找不到完全符合時回傳通用原則。
 * 支援「國語／國文」「數學」「社會」「自然」「英文／英語」等寫法。
 */
export function getSubjectStudyTips(subject: string | undefined | null): string[] {
  if (!subject) return GENERAL_STUDY_TIPS;
  const normalized = subject.trim().toLowerCase();
  const group = SUBJECT_STUDY_TIPS.find((item) =>
    item.matchKeywords.some((keyword) => normalized.includes(keyword.toLowerCase())));
  return group ? group.tips : GENERAL_STUDY_TIPS;
}
