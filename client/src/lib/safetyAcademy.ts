  SAFETY_CARDS.find((card) => card.key === key);

export const getSafetyCardsByHall = (hall: SafetyHallKey): SafetyCard[] =>
  SAFETY_CARDS.filter((card) => card.hall === hall);

export const getSafetyHall = (key: SafetyHallKey): SafetyHall =>
  SAFETY_HALLS.find((hall) => hall.key === key) ?? SAFETY_HALLS[0];
